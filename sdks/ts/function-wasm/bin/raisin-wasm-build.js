/**
 * Build a RaisinDB function component from a JavaScript/TypeScript module.
 *
 * Wraps `jco componentize`. The user's module is never componentized directly:
 * the WIT world exports `handler(name, input)`, so this writes a small entry
 * that imports the user module, wraps it in `createHandler`, and pulls in
 * `host-wit.js` (the one module that imports `raisin:function/host`).
 *
 *   raisin-wasm-build [source] [--out main.wasm] [--world function] [--debug]
 *
 * `http` and `fetch-event` are disabled: egress goes through `raisin.http.*`,
 * which the host polices, never through the guest's own sockets. `clocks`,
 * `random` and `stdio` stay on — `Date.now()` and `Math.random()` are part of
 * the QuickJS surface this SDK promises to reproduce.
 */

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SDK_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const opts = {
    source: null,
    out: 'main.wasm',
    wit: join(SDK_DIR, 'wit'),
    world: 'function',
    debug: false,
    keepEntry: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--out' || arg === '-o') opts.out = argv[++i];
    else if (arg === '--source' || arg === '-s') opts.source = argv[++i];
    else if (arg === '--wit' || arg === '-w') opts.wit = argv[++i];
    else if (arg === '--world' || arg === '-n') opts.world = argv[++i];
    else if (arg === '--debug') opts.debug = true;
    else if (arg === '--keep-entry') opts.keepEntry = true;
    else if (arg === '--help' || arg === '-h') opts.help = true;
    else if (arg.startsWith('-')) fail(`unknown option '${arg}'`);
    else if (!opts.source) opts.source = arg;
    else fail(`unexpected argument '${arg}'`);
  }
  opts.source = opts.source ?? 'src/index.js';
  return opts;
}

function fail(message) {
  console.error(`raisin-wasm-build: ${message}`);
  process.exit(1);
}

/** A relative ESM specifier from `fromFile`'s directory to `target`. */
function specifier(fromFile, target) {
  let rel = relative(dirname(fromFile), target).split('\\').join('/');
  if (!rel.startsWith('.') && !isAbsolute(rel)) rel = `./${rel}`;
  return rel;
}

/**
 * Locate the `jco` CLI.
 *
 * Not via `require.resolve('@bytecodealliance/jco/package.json')`: the package
 * publishes an `exports` map with no `./package.json` entry, so that throws.
 * The `node_modules/.bin/jco` shim is the stable handle — searched from the
 * project being built first, then from this SDK, then `$PATH`.
 */
function jcoBin() {
  const roots = [process.cwd(), SDK_DIR];
  for (const root of roots) {
    let dir = resolve(root);
    for (;;) {
      const candidate = join(dir, 'node_modules', '.bin', 'jco');
      if (existsSync(candidate)) return candidate;
      const parent = dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  }
  return 'jco';
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log(
      'usage: raisin-wasm-build [source] [--out main.wasm] [--wit <dir>] ' +
        '[--world function] [--debug] [--keep-entry]',
    );
    return;
  }

  const source = resolve(opts.source);
  if (!existsSync(source)) fail(`source module '${opts.source}' does not exist`);
  const out = resolve(opts.out);
  const wit = resolve(opts.wit);
  if (!existsSync(wit)) fail(`WIT path '${opts.wit}' does not exist`);

  const entryPath = join(dirname(source), '.raisin-entry.mjs');
  const sdkEntry = join(SDK_DIR, 'src', 'entry.js');
  const sdkHostWit = join(SDK_DIR, 'src', 'host-wit.js');
  writeFileSync(
    entryPath,
    [
      '// GENERATED by raisin-wasm-build — safe to delete.',
      `import '${specifier(entryPath, sdkHostWit)}';`,
      `import { createHandler } from '${specifier(entryPath, sdkEntry)}';`,
      `import * as userModule from '${specifier(entryPath, source)}';`,
      '',
      'export const handler = createHandler(userModule);',
      '',
    ].join('\n'),
  );

  const args = [
    'componentize',
    entryPath,
    '--wit',
    wit,
    '--world-name',
    opts.world,
    '--bundle',
    '--disable',
    'http',
    'fetch-event',
    '--out',
    out,
  ];
  if (opts.debug) args.push('--debug');

  const jco = jcoBin();
  const run = spawnSync(jco, args, { stdio: 'inherit' });
  if (run.error && run.error.code === 'ENOENT') {
    if (!opts.keepEntry) rmSync(entryPath, { force: true });
    fail(
      'jco was not found. Add it to the project: ' +
        '`npm i -D @bytecodealliance/jco @bytecodealliance/componentize-js`',
    );
  }
  if (!opts.keepEntry) rmSync(entryPath, { force: true });
  if (run.status !== 0) fail(`jco componentize failed (exit ${run.status ?? 'signal'})`);

  const bytes = readFileSync(out);
  const sha = createHash('sha256').update(bytes).digest('hex');
  const mib = (bytes.length / (1024 * 1024)).toFixed(2);
  const shown = relative(process.cwd(), out);
  console.log(
    `built ${shown.startsWith('..') ? out : shown}  ${bytes.length} bytes (${mib} MiB)`,
  );
  console.log(`sha256 ${sha}`);
  if (bytes.length > 32 * 1024 * 1024) {
    console.error('WARNING: larger than the server default artifact cap of 32 MiB');
  }
}

main();
